"""TRIO's band scenarios for the host simulator (app/tests/*.txt), timed to the millisecond.

A player plays chords a little before each bar (as a pianist does: 150 ms, a third of a beat at 140), over MIDI:
the A section of Autumn Leaves, round and round. The scenario checks that the band starts, follows the chords,
learns the 8-bar form, guesses from it, never misses a beat, and sounds.

  python3 tools/make_scenarios.py        writes app/tests/band.txt, teach.txt and screens.txt

teach.txt: EDIT, teaching the bass a walking line, and what the bass plays after (see teach()).
"""
from pathlib import Path

BPM = 140
BEAT = 60000.0 / BPM
BAR = 4 * BEAT
LEAD = 150.0                       # the chord, this many ms before its bar line
START = 1.0 + 3.0 + 4 * BEAT       # beat 0 after PLAY's press: the next ms, the next audio block (~3 ms), the count-in

# the A section of Autumn Leaves in G minor, root lowest (MIDI notes); (name, root pitch class, kind: trio_nn.h Q_*)
Q_MAJ, Q_DOM, Q_MIN, Q_HDIM = 0, 1, 2, 3
A = [("Cm7", [48, 51, 55, 58], 0, Q_MIN), ("F7", [53, 57, 60, 63], 5, Q_DOM),
     ("Bbmaj7", [46, 50, 53, 57], 10, Q_MAJ), ("Ebmaj7", [51, 55, 58, 62], 3, Q_MAJ),
     ("Am7b5", [45, 48, 51, 55], 9, Q_HDIM), ("D7", [50, 54, 57, 60], 2, Q_DOM),
     ("Gm7", [43, 46, 50, 53], 7, Q_MIN), ("Gm7", [43, 46, 50, 53], 7, Q_MIN)]


class Script:
    def __init__(self):
        self.t = 0.0                # ms since PLAY's press (the script's own clock)
        self.lines = []

    def say(self, s):
        self.lines.append(s)

    def wait_until(self, t):
        ms = int(round(t - self.t))
        if ms > 0:
            self.say(f"wait {ms}")
            self.t += ms

    def midi(self, *b, port=""):
        self.say("midi " + (port + " " if port else "") + " ".join(f"{x:02X}" for x in b))
        self.t += 2                 # the simulator runs 2 ms after each message


def band():
    s = Script()
    s.say("# TRIO's band in the host simulator (generated by tools/make_scenarios.py: edit that, not this):")
    s.say("#   ./build.sh --host && app/build/host/trio_host app/tests/band.txt app/build/host")
    s.say("# Autumn Leaves' A section at 140, each chord 150 ms before its bar, four times round")
    s.say("wait 600")
    s.say("expect state 0")
    s.say("tap PLAY")
    s.t = 80.0                      # (tap: 40 ms down, 40 up; the press counts from its first ms)
    s.say("expect state 1")
    held = []
    for bar in range(32):
        name, notes, root, kind = A[bar % 8]
        on = START + bar * BAR - LEAD
        s.wait_until(on - 2 * len(held) - 4)
        for n in held:              # the last chord let go just before the next
            s.midi(0x80, n, 0)
        s.wait_until(on)
        port = "TRS" if bar == 5 else ""   # one chord from a keyboard on the TRS jack
        for n in notes:
            s.midi(0x90, n, 80, port=port)
        held = notes
        if bar == 0:
            s.wait_until(START + BEAT)
            s.say("expect state 2")
            s.say(f"expect root {root}")
            s.say(f"expect qual {kind}")
            s.say("expect feel_now 1")          # AUTO: in two until the form comes round
            s.say("expect next 0")
        if bar == 5:
            s.wait_until(START + 5 * BAR + BEAT)
            s.say(f"expect root {root}")        # (the TRS chord)
            s.say(f"expect qual {kind}")
        if bar == 16:
            s.wait_until(START + 16 * BAR + 5)
            s.say("wav band.wav")
        if bar == 24:
            s.wait_until(START + 24 * BAR + 5)
            s.say("wavstop")
            s.say("expect peak_db_min -24")     # the band sounds
            s.say("expect peak_db_max -0.5")    # and does not clip
            s.say("expect form 8")              # the form learned: 8 bars
            s.say("expect feel_now 2")          # and the band in four
            s.say("shot band-playing.png")
        if bar == 30:
            s.wait_until(START + 30 * BAR + 2 * BEAT)
            s.say("expect next 1")              # what comes next, from the form
            s.say(f"expect root {root}")
            s.say("expect bass >27")
            s.say("expect bass <56")
            s.say("expect missed 0")
            s.say("expect nnsteps >400")
    s.wait_until(START + 32 * BAR + 2 * BEAT)
    # the player stops: the form keeps the band going on its own
    for n in held:
        s.midi(0x80, n, 0)
    s.wait_until(START + 34 * BAR + BEAT)
    s.say("expect state 2")
    s.say("expect root 10")                     # bar 34 is Bbmaj7's, from the form alone
    s.say("expect missed 0")
    s.say("tap PLAY")
    s.say("wait 50")
    s.say("expect state 0")
    # REC: a new tune, the form forgotten
    s.say("tap REC")
    s.say("wait 30")
    s.say("expect form 0")
    return "\n".join(s.lines) + "\n"


def line(chart):
    """the player's walking line over a chart (a (root, kind) a beat): on each chord R 5 8 and, on its last beat, the
    half step above the next chord's root (two beats: R and that approach), the roots from G1 to F#2; a pickup (a
    ghost of the same note on the swung eighth) into each change after a bar or more. As tests/host/teach_test.c"""
    n_b, out, b = len(chart), [], 0
    while b < n_b:
        e = b
        while e < n_b and chart[e] == chart[b]:
            e += 1
        n = e - b
        r, nr = 31 + (chart[b][0] - 7) % 12, 31 + (chart[e % n_b][0] - 7) % 12
        fifth = 6 if chart[b][1] == Q_HDIM else 7
        for i in range(n):
            note = nr + 1 if n > 1 and i == n - 1 else r + (fifth if i % 2 else 12 if i % 4 == 2 else 0)
            out.append((note, n >= 4 and i == n - 1))
        b = e
    return out


def teach():
    """EDIT: the band learns the form, plays a chorus alone, then the player teaches it a walking line (two choruses:
    over MIDI, then on the FM-1's keys two octaves down); EDIT again, it learns the line, and the band walks it"""
    s = Script()
    chart = [(c[2], c[3]) for c in A for _ in range(4)]
    taught = line(chart)
    jit = [((i * 7919) % 41) - 20 for i in range(256)]   # each note up to 20 ms off its beat

    def at(beat):
        return START + beat * BEAT

    def chords(bars, notes_of, first=0):
        held = []
        for bar in range(first, first + bars):
            notes = notes_of(bar)
            on = at(4 * bar) - LEAD
            s.wait_until(on - 2 * len(held) - 4)
            for n in held:
                s.midi(0x80, n, 0)
            s.wait_until(on)
            for n in notes:
                s.midi(0x90, n, 80)
            held = notes
        return held

    def play_line(b0, nbeats, keys=False, prev=None):
        """the line from beat b0: MIDI notes, or the FM-1's keys (OCT -2: key k is note 29 + k), legato (prev: the
        note sounding before it)"""

        def on(n, vel):
            if keys:
                s.say(f"key {n - 29} down {vel}")
                s.t += 2
            else:
                s.midi(0x90, n, vel)

        def off(n):
            if keys:
                s.say(f"key {n - 29} up")
                s.t += 2
            else:
                s.midi(0x80, n, 0)

        for b in range(b0, b0 + nbeats):
            note, ghost = taught[b % len(taught)]
            s.wait_until(at(b) + jit[b % 256])
            on(note, 84)
            if prev is not None:                 # the note before lets go just after: legato
                off(prev)
            prev = note
            if ghost:                            # the pickup: the same note again on the swung eighth, quietly
                s.wait_until(at(b + 0.64) - 4)
                off(note)
                on(note, 36)
        return prev

    s.say("# TRIO's EDIT: teaching the bass in the host simulator (generated by tools/make_scenarios.py: edit that,")
    s.say("# not this):  ./build.sh --host && app/build/host/trio_host app/tests/teach.txt app/build/host")
    s.say("# Autumn Leaves' A section at 140: the chords three times round (the form), the band alone a chorus, then a")
    s.say("# walking line taught two choruses (R 5 8 and the half step above the next root, pickups into the changes;")
    s.say("# over MIDI, then on the keys), learned, and the band on: how often its bass plays the taught note, before")
    s.say("# and after. Then kept (SAVE, a restart), taught on top while stopped, forgotten (EDIT held), too short.")
    s.say("wait 600")
    s.say("listen")
    s.say("wait 100")
    s.say("expect learned 0")
    s.say("expect bass_unsaved 0")
    s.say("tap PLAY")
    s.t = 80.0
    held = chords(24, lambda bar: A[bar % 8][1])
    s.wait_until(at(96) - LEAD)
    for n in held:                               # the pianist lets go: the band goes on with the form
        s.midi(0x80, n, 0)
    s.wait_until(at(96) + 20)
    s.say("expect form 8")
    s.say("expect feel_now 2")
    # a beat before bar 32: EDIT, teaching (its tap acts as it is let go)
    s.wait_until(at(127) - 40)
    s.say("tap EDIT")
    s.t += 80
    s.say("said TEACH BASS PLAY THE LINE")
    s.say("expect teaching 1")
    s.say("expect taught 0")
    last = play_line(128, 25)
    s.wait_until(at(152) + 60)
    s.say("expect taught >20")
    s.say(f"expect bass {taught[24][0]}")        # the bass is the player's: the note on beat 24's
    s.say(f"expect root {A[6][2]}")              # (and the line's notes are not heard as chords: Gm7, the form's)
    s.say("shot teach.png")
    last = play_line(153, 7, prev=last)
    s.wait_until(at(160) - 0.3 * BEAT)
    s.midi(0x80, last, 0)
    s.say("tap OCT-")                            # the keys two octaves down: F1 .. G3
    s.say("tap OCT-")
    s.t += 160
    s.say("expect octave -2")
    s.wait_until(at(160) - 30)
    last = play_line(160, 32, keys=True)
    s.wait_until(at(192) - 0.1 * BEAT - 40)      # just after the last beat: EDIT again, it learns the line
    s.say(f"key {last - 29} up")
    s.t += 2
    s.say("tap EDIT")
    s.t += 80
    s.say("said LEARNING 16 BARS")
    s.say("expect teaching 0")
    s.say("expect learning 1")
    s.say("tap EDIT")                            # (a lesson while it learns: not yet)
    s.t += 80
    s.say("said STILL LEARNING")
    s.say("expect teaching 0")
    s.wait_until(at(196))
    s.say("said LEARNED YOUR LINE")
    s.say("expect learning 0")
    s.say("expect learned 1")
    s.say("expect bass_unsaved 1")
    s.wait_until(at(260))                        # the band on, two choruses and more with the bass as it learned
    s.say("expect agree_before <35")
    s.say("expect agree_after >40")
    s.say("expect missed 0")
    s.say("shot teach-learned.png")
    s.say("tap PLAY")
    s.say("wait 50")
    s.say("expect state 0")
    s.say("tap SAVE")                            # kept: the settings and what the bass learned
    s.say("wait 30")
    s.say("expect bass_unsaved 0")
    s.say("expect store_writes 2")
    s.say("reboot")
    s.say("wait 600")
    s.say("expect learned 1")
    s.say("expect bass_unsaved 0")
    # stopped: EDIT arms the teaching, PLAY counts in; over the player's own chords (from Ab3 up: below them is the
    # line); the reader hears it; STOP learns the line, on top of what the bass learned
    s.say("tap OCT+")
    s.say("tap OCT+")
    s.say("wait 30")
    s.say("listen")
    s.say("wait 100")
    s.say("tap EDIT")
    s.say("said TEACH BASS PRESS PLAY")
    s.say("expect teaching 1")
    s.say("tap PLAY")
    s.t = 80.0
    s.say("said TEACH BASS COUNT IN")
    high = {0: [60, 63, 67, 70], 5: [65, 69, 72, 75], 10: [58, 62, 65, 69], 3: [63, 67, 70, 74], 9: [57, 60, 63, 67],
            2: [62, 66, 69, 72], 7: [67, 70, 74, 77]}
    held = []
    for bar in range(4):                         # four bars of chords and the line together
        notes = high[A[bar][2]]
        s.wait_until(at(4 * bar) - LEAD - 2 * len(held) - 4)
        for n in held:
            s.midi(0x80, n, 0)
        s.wait_until(at(4 * bar) - LEAD)
        for n in notes:
            s.midi(0x90, n, 80)
        held = notes
        last = play_line(4 * bar, 4)
        if bar == 1:
            s.say("where")
            s.say("said TEACHING THE BASS")
    s.wait_until(at(16) - 0.1 * BEAT)
    s.midi(0x80, last, 0)
    for n in held:
        s.midi(0x80, n, 0)
    s.say(f"expect root {A[3][2]}")              # Ebmaj7 from the player's chord, from Ab3 up
    s.say("tap PLAY")
    s.say("said LEARNING 4 BARS")                # (four bars learn in 40 ms in the simulator, a slice each ms)
    s.say("wait 1500")
    s.say("expect learning 0")
    s.say("expect learned 2")
    s.say("expect state 0")
    # EDIT held 1.5 s: the bass as trained; kept so too
    s.say("press EDIT")
    s.say("wait 1600")
    s.say("said BASS AS TRAINED")
    s.say("release EDIT")
    s.say("wait 30")
    s.say("unsaid TEACH")
    s.say("expect learned 0")
    s.say("expect teaching 0")
    s.say("expect bass_unsaved 1")
    s.say("tap SAVE")
    s.say("wait 30")
    s.say("expect bass_unsaved 0")
    s.say("reboot")
    s.say("wait 600")
    s.say("expect learned 0")
    # a lesson with too few notes teaches nothing
    s.say("tap PLAY")
    s.say("wait 2000")
    s.say("tap EDIT")
    s.say("wait 2000")
    s.say("tap EDIT")
    s.say("said NOTHING LEARNED PLAY A LINE")
    s.say("expect learning 0")
    s.say("expect learned 0")
    s.say("tap PLAY")
    s.say("wait 50")
    s.say("expect state 0")
    s.say("expect missed 0")
    return "\n".join(s.lines) + "\n"


def screens():
    s = Script()
    s.say("# The manual's screenshots (app/docs/img; generated by tools/make_scenarios.py):")
    s.say("#   ./build.sh --host && app/build/host/trio_host app/tests/screens.txt app/docs/img")
    s.say("wait 900")
    s.say("shot screen-ready.png")
    s.say("tap PLAY")
    s.t = 80.0
    held = []
    for bar in range(26):
        notes = A[bar % 8][1]
        on = START + bar * BAR - LEAD
        s.wait_until(on - 2 * len(held) - 4)
        for n in held:
            s.midi(0x80, n, 0)
        s.wait_until(on)
        for n in notes:
            s.midi(0x90, n, 80)
        held = notes
        if bar == 2:                # the first time round: learning, the network's guess
            s.wait_until(START + 2 * BAR + 2 * BEAT + 30)
            s.say("shot screen-learning.png")
        if bar == 25:               # the form learned: what comes next, from it
            s.wait_until(START + 25 * BAR + 1 * BEAT + 30)
            s.say("shot screen-playing.png")
    s.say("tap GLO")
    s.say("wait 1400")
    s.say("shot screen-mix.png")
    s.say("tap SEL")                # the Bluetooth page: the simulator's stand-in device found, then connected
    s.say("wait 700")
    s.say("tap SEL")
    s.say("wait 1700")
    s.say("shot screen-bluetooth.png")
    s.say("tap GLO")
    s.t += 4 * 80 + 1400 + 700 + 1700           # (the taps and waits since the last shot)
    # EDIT: teaching the bass two bars, from the next bar line, the chord let go (the band goes on with the form)
    for n in held:
        s.midi(0x80, n, 0)
    taught = line([(c[2], c[3]) for c in A for _ in range(4)])
    bar = int((s.t - START) / BAR) + 2
    s.wait_until(START + bar * BAR - BEAT - 40)
    s.say("tap EDIT")
    prev = None
    for b in range(4 * bar, 4 * bar + 9):
        s.wait_until(START + b * BEAT)
        s.midi(0x90, taught[b % 32][0], 84)
        if prev is not None:
            s.midi(0x80, prev, 0)
        prev = taught[b % 32][0]
    s.wait_until(START + (4 * bar + 8) * BEAT + 60)
    s.say("shot screen-teaching.png")
    s.midi(0x80, prev, 0)
    s.say("tap EDIT")
    s.say("wait 1500")
    s.say("tap PLAY")
    s.say("wait 50")
    return "\n".join(s.lines) + "\n"


if __name__ == "__main__":
    tests = Path(__file__).resolve().parents[1] / "app" / "tests"
    for name, text in (("band.txt", band()), ("teach.txt", teach()), ("screens.txt", screens())):
        (tests / name).write_text(text)
        print(tests / name)
